#!/usr/bin/env node
/*
  install-exam-pages.mjs  —  safe, re-runnable installer
  -------------------------------------------------------
  Run from the uploadsure repo root:   node tools/install-exam-pages.mjs

  1. CHECKS your current files (nothing written yet):
     - repo looks right, git working tree is clean (so you can undo)
     - the helper functions the new pages need still exist in your JS
     - no existing page of yours would be overwritten
  2. Only if every check passes:
     - appends the exam-page CSS block to styles.css (once)
     - adds one "All 20 Exams" link to the header menu (once)
     - generates the 21 pages and ADDS them to sitemap.xml
       (your existing sitemap entries are kept as they are)

  Undo everything:  git checkout -- . && git clean -fd
*/

import fs from "node:fs";
import path from "node:path";
import { execSync } from "node:child_process";

const ROOT = process.cwd();
const FORCE = process.argv.includes("--force");
const read = (f) => fs.readFileSync(path.join(ROOT, f), "utf8");
const exists = (f) => fs.existsSync(path.join(ROOT, f));
const problems = [];
const notes = [];

/* ---- 1. repo sanity ---- */
for (const f of ["index.html", "styles.css", "sitemap.xml", "js/utils.js", "js/worker-client.js",
  "js/image-worker.js", "js/header.js", "data/exams.json", "tools/build-exam-pages.mjs", "js/exam-page.js",
  "tools/exam-pages.css"]) {
  if (!exists(f)) problems.push(`Missing file: ${f}`);
}
if (problems.length) finish();

try {
  const dirty = execSync("git status --porcelain", { cwd: ROOT }).toString().trim();
  const ours = /^(\?\?|A |M ) ?(data\/|tools\/|js\/exam-page\.js)/;
  const others = dirty.split("\n").filter((l) => l && !ours.test(l.trim()));
  if (others.length && !FORCE) problems.push(
    "You have uncommitted changes. Commit them first so this install can be undone cleanly:\n      " +
    others.slice(0, 10).join("\n      ") + "\n    (or re-run with --force)");
} catch { notes.push("Not a git repo or git not found — skipping clean-tree check."); }

/* ---- 2. functions the new pages call ---- */
const utils = read("js/utils.js"), wc = read("js/worker-client.js"), worker = read("js/image-worker.js");
for (const fn of ["coverCropToCanvas", "loadImageFromFile", "formatKilobytes", "triggerDownload",
  "sampleBorderForPlainBackground", "checkmarkIcon", "warningIcon", "showToast", "bindDropZone",
  "initThemeToggle", "initScrollToTop"]) {
  if (!new RegExp(`function\\s+${fn}\\s*\\(`).test(utils)) problems.push(`js/utils.js no longer has function ${fn}()`);
}
if (!/function\s+workerCompressFixedDimensions\s*\(/.test(wc)) problems.push("js/worker-client.js no longer has workerCompressFixedDimensions()");
if (!/compressFixedDimensions/.test(worker)) problems.push("js/image-worker.js no longer handles compressFixedDimensions");
for (const f of ["js/cookie-consent.js", "js/header.js", "js/footer.js", "js/pwa-install.js", "js/search.js", "js/sticky-header.js"]) {
  if (!exists(f)) problems.push(`Pages include ${f} but it is missing`);
}
if (exists("js/pwa-install.js") && !/function\s+initPwaInstall/.test(read("js/pwa-install.js"))) problems.push("js/pwa-install.js has no initPwaInstall()");

/* ---- 3. never overwrite one of YOUR pages ---- */
const data = JSON.parse(read("data/exams.json"));
const targets = ["exam-photo-size.html", ...data.exams.map((e) => `${e.slug}.html`)];
for (const f of targets) {
  if (exists(f) && !/id="exam-spec"|tools\/build-exam-pages|ItemList/.test(read(f))) {
    problems.push(`${f} already exists and was not made by this generator — not touching it`);
  }
}

finishIfProblems();

/* ---- 4. apply (idempotent) ---- */
const MARK = "EXAM PAGES (generated by tools/build-exam-pages.mjs)";
let css = read("styles.css");
if (!css.includes(MARK)) {
  fs.writeFileSync(path.join(ROOT, "styles.css"), css.replace(/\s*$/, "\n\n") + read("tools/exam-pages.css"));
  notes.push("styles.css: appended exam-page block at the end (nothing else changed)");
} else notes.push("styles.css: exam-page block already present — skipped");

let header = read("js/header.js");
if (!header.includes("exam-photo-size.html")) {
  const m = header.match(/\n([ \t]*)\{ href: "application-pack\.html\?portal=kyc"[^\n]*\n/);
  if (m) {
    const line = `${m[1]}{ href: "exam-photo-size.html", icon: icon('<path d="M5 12h14M12 5l7 7-7 7"/>'), title: "All Exams →", desc: "Photo & signature size for every exam" },\n`;
    header = header.replace(m[0], m[0] + line);
    fs.writeFileSync(path.join(ROOT, "js/header.js"), header);
    notes.push("js/header.js: added one 'All Exams →' menu item after Bank KYC");
  } else notes.push("js/header.js: Bank KYC menu line not found (you changed the menu) — skipped. Add a link to exam-photo-size.html yourself.");
} else notes.push("js/header.js: link already present — skipped");

execSync("node tools/build-exam-pages.mjs", { cwd: ROOT, stdio: "inherit" });
notes.push(`Generated ${targets.length} pages; sitemap.xml: your entries kept, ${targets.length} added`);

console.log("\n✅ Done.\n  - " + notes.join("\n  - ") +
  "\n\nCheck:  git status   /   git diff styles.css js/header.js sitemap.xml" +
  "\nPreview: python -m http.server 8000  →  http://localhost:8000/exam-photo-size.html" +
  "\nUndo:   git checkout -- . && git clean -fd\n");

function finishIfProblems() { if (problems.length) finish(); }
function finish() {
  console.log("\n❌ Nothing was changed. Fix these first:\n  - " + problems.join("\n  - ") + "\n");
  if (notes.length) console.log("Notes:\n  - " + notes.join("\n  - "));
  process.exit(1);
}
